    @staticmethod
    def determinarZona(x, y):
        esquinas = []
        for punto in Esquina:
            if punto.value[0] >= x[0] and punto.value[0] <= x[1]:
                if punto.value[1] >= y[0] and punto.value[1] <= y[1]:
                    if x[1] == 0 and "CLL10" in punto.name: continue
                    if x[0] == 0 and "CLL9" in punto.name: continue
                    esquinas.append(punto)
        return esquinas
    
